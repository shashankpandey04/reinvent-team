import { NextResponse } from "next/server"
import { backendFetch, backendJson } from "@/lib/api/backend"

export async function GET() {
  try {
    const response = await backendFetch("/api/v1/attendance/checkpoints")
    if (!response.ok) {
      const err = await response.json().catch(() => ({ detail: "Failed to load checkpoints" }))
      return NextResponse.json({ message: err.detail }, { status: response.status })
    }
    const data = await backendJson(response)
    return NextResponse.json(data)
  } catch (err) {
    return NextResponse.json(
      { message: err instanceof Error ? err.message : "Error loading checkpoints" },
      { status: 500 }
    )
  }
}
